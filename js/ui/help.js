/* 使い方（アプリ内ヘルプ）。
   球場でも見られるよう、外部ページではなくアプリに内蔵する。
   長文にせず、項目ごとに畳んで必要なところだけ開ける形にする。 */

import { html, raw, esc, render, on } from './common.js';
import { go } from './router.js';

/** 見出しと中身を1つの折りたたみにする */
function section(title, body, opened = false) {
  return `<details class="help" ${opened ? 'open' : ''}>
    <summary>${esc(title)}</summary>
    <div class="help-body">${body}</div>
  </details>`;
}

/** 手順を番号付きで並べる */
function steps(items) {
  return `<ol class="help-steps">${items.map((s) => `<li>${s}</li>`).join('')}</ol>`;
}

/** 操作と説明の対応表 */
function table(rows) {
  return `<table class="help-table"><tbody>
    ${rows.map(([k, v]) => `<tr><th>${esc(k)}</th><td>${v}</td></tr>`).join('')}
  </tbody></table>`;
}

